/**
 * Asset manifest generator. `npm run gen:assets`
 *
 * Metro can only bundle files that are `require()`d with a literal path, so this tool scans
 *   src/content/packs/<packId>/{audio,images}/**   -> src/content/packs/assets.generated.ts
 *   src/audio/prompts/<lang>/<promptId>.m4a         -> src/audio/prompts.generated.ts
 * and writes static require() maps keyed `<packId>/<relative path>` and `<lang>/<promptId>`.
 *
 * Output is sorted and prettier-formatted, and files are only rewritten when the content changes,
 * so CI can run it and fail on a diff. Sound effects are synthesised (ADR 0001 point 7): no files.
 */
import fs from 'node:fs';
import path from 'node:path';

import { PACK_ID_RE } from '../src/content/schema';

const ROOT = path.resolve(__dirname, '..');
const PACKS_DIR = path.join(ROOT, 'src/content/packs');
const PROMPTS_DIR = path.join(ROOT, 'src/audio/prompts');

const PACK_EXT = /\.(m4a|webp|png)$/;
const PROMPT_EXT = /\.m4a$/;

/** Recursively lists files under `dir`, relative to it, with forward slashes, sorted. */
export function listFiles(dir: string, filter: RegExp): string[] {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const out: string[] = [];
  const walk = (rel: string) => {
    for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        walk(r);
      } else if (filter.test(entry.name)) {
        out.push(r);
      }
    }
  };
  walk('');
  return out.sort();
}

/** Builds the TypeScript source of a manifest: entries are [key, require path]. */
export function manifestSource(
  exportName: string,
  keyDoc: string,
  entries: [string, string][],
): string {
  const sorted = [...entries].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const body = sorted.map(
    ([key, file]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(file)}),`,
  );
  return [
    '/* eslint-disable */',
    '// GENERATED by tools/gen-asset-manifest.ts. Do not edit by hand. Run `npm run gen:assets`.',
    `// Maps ${keyDoc} to a bundled asset module (require()).`,
    body.length
      ? `export const ${exportName}: Record<string, number> = {\n${body.join('\n')}\n};`
      : `export const ${exportName}: Record<string, number> = {};`,
    '',
  ].join('\n');
}

export function packEntries(packsDir: string): [string, string][] {
  const entries: [string, string][] = [];
  const ids = fs
    .readdirSync(packsDir, { withFileTypes: true })
    .filter(d => d.isDirectory() && PACK_ID_RE.test(d.name))
    .map(d => d.name)
    .sort();
  for (const id of ids) {
    for (const sub of ['audio', 'images']) {
      for (const rel of listFiles(path.join(packsDir, id, sub), PACK_EXT)) {
        entries.push([`${id}/${sub}/${rel}`, `./${id}/${sub}/${rel}`]);
      }
    }
  }
  return entries;
}

export function promptEntries(promptsDir: string): [string, string][] {
  const entries: [string, string][] = [];
  if (!fs.existsSync(promptsDir)) {
    return entries;
  }
  const langs = fs
    .readdirSync(promptsDir, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name)
    .sort();
  for (const lang of langs) {
    for (const rel of listFiles(path.join(promptsDir, lang), PROMPT_EXT)) {
      if (rel.includes('/')) {
        continue; // prompts are flat: <lang>/<promptId>.m4a
      }
      entries.push([`${lang}/${rel.replace(PROMPT_EXT, '')}`, `./prompts/${lang}/${rel}`]);
    }
  }
  return entries;
}

async function writeIfChanged(file: string, source: string): Promise<void> {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(file)) ?? {};
  const formatted = await prettier.format(source, { ...options, filepath: file });
  const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  if (before === formatted) {
    console.warn(`= ${rel}`);
    return;
  }
  fs.writeFileSync(file, formatted);
  console.warn(`✎ ${rel}`);
}

async function main() {
  const packs = packEntries(PACKS_DIR);
  const prompts = promptEntries(PROMPTS_DIR);
  await writeIfChanged(
    path.join(PACKS_DIR, 'assets.generated.ts'),
    manifestSource('PACK_ASSETS', '`<packId>/<relative path>`', packs),
  );
  await writeIfChanged(
    path.join(ROOT, 'src/audio/prompts.generated.ts'),
    manifestSource('PROMPT_ASSETS', '`<lang>/<promptId>`', prompts),
  );
  console.warn(`${packs.length} pack assets, ${prompts.length} voice prompts`);
}

if (require.main === module) {
  main().catch(e => {
    console.error(e);
    process.exit(1);
  });
}
