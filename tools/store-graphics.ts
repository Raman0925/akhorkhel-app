/**
 * Store graphics + launcher icons. `npm run store:graphics`
 *
 * Renders from the hand-written mascot (assets/brand/mascot-rhino.svg) and the letters shaped from
 * the app's Noto Sans Bengali (HarfBuzz → path, so resvg never needs a system font):
 *   - docs/store/graphics/icon-512.png               Play icon, 512 × 512, 32-bit
 *   - docs/store/graphics/feature-graphic-1024x500.png  Play feature graphic, 24-bit (no alpha)
 *   - assets/brand/icon.svg, assets/brand/feature-graphic.svg  the composed sources (generated)
 *   - android/app/src/main/res/mipmap-<density>/ic_launcher.png + ic_launcher_round.png (legacy)
 *   - android/app/src/main/res/mipmap-<density>/ic_launcher_foreground.png (adaptive foreground)
 *   - android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml + ic_launcher_round.xml
 *   - android/app/src/main/res/drawable/ic_launcher_monochrome.xml (themed icon, vector "ক")
 *   - android/app/src/main/res/values/ic_launcher_background.xml
 *
 * The icon is designed in a 100-unit "content box" whose important parts stay inside a circle of
 * radius ~46 around the centre: the Play icon shows the box full-bleed (Play masks the corners),
 * the adaptive foreground maps it onto the 72 dp visible area of the 108 dp layer.
 */
import fs from 'node:fs';
import path from 'node:path';

import type { GeometryFile } from '../src/content/schema';
import {
  BRAND,
  FONT_FILES,
  ROOT,
  glyphUnit,
  mascotAt,
  pathAt,
  textPath,
  type TextStyle,
} from './store/brand';
import { encodeRgbPng } from './store/png';

const OUT_DIR = path.join(ROOT, 'docs/store/graphics');
const BRAND_DIR = path.join(ROOT, 'assets/brand');
const RES_DIR = path.join(ROOT, 'android/app/src/main/res');

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 } as const;

type Glyph = Awaited<ReturnType<typeof glyphUnit>>;

async function render(svg: string, width: number): Promise<{ png: Buffer; pixels: Uint8Array }> {
  const { Resvg } = await import('@resvg/resvg-js');
  const img = new Resvg(svg, {
    fitTo: { mode: 'width', value: width },
    font: { loadSystemFonts: false, fontFiles: FONT_FILES, defaultFontFamily: 'Noto Sans' },
    shapeRendering: 2,
    textRendering: 1,
  }).render();
  return { png: img.asPng(), pixels: new Uint8Array(img.pixels) };
}

// ---- Icon --------------------------------------------------------------------------------------

/** The icon artwork in the 100-unit content box (no background). */
function iconContent(ka: Glyph): string {
  // "ক" top right in gamosa red with a white rim; the rhino in front, lower left, body running
  // off the bottom edge.
  const kaSize = 39;
  const kx = 46;
  const ky = 19;
  const ka1 = pathAt(ka, kx, ky, kaSize);
  return [
    `<path d="${ka1}" fill="${BRAND.surface}" stroke="${BRAND.surface}" stroke-width="7" stroke-linejoin="round"/>`,
    `<path d="${ka1}" fill="${BRAND.primary}" stroke="${BRAND.primary}" stroke-width="1.2" stroke-linejoin="round"/>`,
    mascotAt(-3, 34, 70, true),
  ].join('');
}

function iconSvg(
  ka: Glyph,
  opts: { background: boolean; shape?: 'square' | 'rounded' | 'circle' },
) {
  const bg = !opts.background
    ? ''
    : opts.shape === 'circle'
      ? `<circle cx="50" cy="50" r="50" fill="${BRAND.sun}"/>`
      : opts.shape === 'rounded'
        ? `<rect width="100" height="100" rx="18" fill="${BRAND.sun}"/>`
        : `<rect width="100" height="100" fill="${BRAND.sun}"/>`;
  const clip =
    opts.shape === 'circle'
      ? '<clipPath id="c"><circle cx="50" cy="50" r="50"/></clipPath>'
      : opts.shape === 'rounded'
        ? '<clipPath id="c"><rect width="100" height="100" rx="18"/></clipPath>'
        : '<clipPath id="c"><rect width="100" height="100"/></clipPath>';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">` +
    `<defs>${clip}</defs><g clip-path="url(#c)">${bg}${iconContent(ka)}</g></svg>`
  );
}

/** Adaptive foreground: 108 × 108 dp layer, the content box on the central 72 dp. */
function foregroundSvg(ka: Glyph): string {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">` +
    `<defs><clipPath id="c"><rect width="108" height="108"/></clipPath></defs>` +
    `<g clip-path="url(#c)"><g transform="translate(18 18) scale(0.72)">${iconContent(ka)}</g></g></svg>`
  );
}

/** Themed-icon layer: "ক" alone as a vector drawable inside the 66 dp safe zone. */
function monochromeXml(ka: Glyph): string {
  const size = 46;
  const d = pathAt(ka, 54 - size / 2, 54 - size / 2, size);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-graphics.ts (npm run store:graphics). Themed-icon layer: the letter ক. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FF000000"
        android:pathData="${d}" />
</vector>
`;
}

const ADAPTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-graphics.ts (npm run store:graphics). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

const BACKGROUND_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-graphics.ts (npm run store:graphics). -->
<resources>
    <color name="ic_launcher_background">${BRAND.sun}</color>
</resources>
`;

// ---- Feature graphic ---------------------------------------------------------------------------

type Pt = [number, number];

/** Point at fraction t of a polyline's length, plus the direction there. */
function along(pts: Pt[], t: number): { p: Pt; dir: Pt; upto: Pt[] } {
  const seg: number[] = [];
  let total = 0;
  for (let i = 1; i < pts.length; i++) {
    const a = pts[i - 1] as Pt;
    const b = pts[i] as Pt;
    const l = Math.hypot(b[0] - a[0], b[1] - a[1]);
    seg.push(l);
    total += l;
  }
  let want = total * t;
  const upto: Pt[] = [pts[0] as Pt];
  for (let i = 1; i < pts.length; i++) {
    const a = pts[i - 1] as Pt;
    const b = pts[i] as Pt;
    const l = seg[i - 1] as number;
    if (want <= l || i === pts.length - 1) {
      const f = l === 0 ? 0 : Math.min(1, want / l);
      const p: Pt = [a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f];
      upto.push(p);
      return { p, dir: [(b[0] - a[0]) / (l || 1), (b[1] - a[1]) / (l || 1)], upto };
    }
    want -= l;
    upto.push(b);
  }
  return { p: pts[pts.length - 1] as Pt, dir: [1, 0], upto };
}

function polyline(pts: Pt[], x: number, y: number, s: number): string {
  return pts
    .map(([px, py], i) => `${i ? 'L' : 'M'}${(x + px * s).toFixed(1)} ${(y + py * s).toFixed(1)}`)
    .join('');
}

async function featureSvg(): Promise<string> {
  const geometry = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'src/content/packs/asm-beng/geometry.json'), 'utf8'),
  ) as GeometryFile;
  const a = geometry['letter:a'];
  if (!a) {
    throw new Error('geometry.json has no letter:a');
  }
  const W = 1024;
  const H = 500;
  // Tracing card (same look as the app's TraceCanvas: white box, faint letter, dashed guides,
  // green start dot, numbered strokes, blue ink, red arrow).
  const card = { x: 112, y: 84, s: 332 };
  const { x, y, s } = card;
  const strokes = a.strokes.map(st => st.points as Pt[]);
  const parts: string[] = [];
  parts.push(
    `<rect x="${x - 10}" y="${y + 8}" width="${s}" height="${s}" rx="34" fill="${BRAND.accent}" opacity="0.35"/>`,
    `<rect x="${x}" y="${y}" width="${s}" height="${s}" rx="30" fill="${BRAND.surface}" stroke="${BRAND.border}" stroke-width="4"/>`,
    `<g transform="translate(${x} ${y}) scale(${s})"><path d="${a.outline}" fill="${BRAND.guide}" opacity="0.35"/></g>`,
  );
  strokes.forEach((st, i) => {
    parts.push(
      `<path d="${polyline(st, x, y, s)}" fill="none" stroke="${i === 0 ? BRAND.textMuted : BRAND.guide}" stroke-width="${i === 0 ? 6 : 4.5}" stroke-linecap="round" stroke-linejoin="round" stroke-dasharray="12 10"/>`,
    );
  });
  // Ink along most of stroke 1, then the arrow showing where to go next.
  const first = strokes[0] as Pt[];
  const ink = along(first, 0.62);
  parts.push(
    `<path d="${polyline(ink.upto, x, y, s)}" fill="none" stroke="${BRAND.ink}" stroke-width="20" stroke-linecap="round" stroke-linejoin="round"/>`,
  );
  const start = first[0] as Pt;
  parts.push(
    `<circle cx="${x + start[0] * s}" cy="${y + start[1] * s}" r="14" fill="${BRAND.startDot}"/>`,
  );
  const ahead = along(first, 0.78);
  const ang = (Math.atan2(ahead.dir[1], ahead.dir[0]) * 180) / Math.PI;
  parts.push(
    `<g transform="translate(${x + ahead.p[0] * s} ${y + ahead.p[1] * s}) rotate(${ang.toFixed(1)})"><path d="M14 0 L-12 -14 L-6 0 L-12 14 Z" fill="${BRAND.arrow}"/></g>`,
  );
  for (const [i, st] of strokes.entries()) {
    const p = st[0] as Pt;
    const label = await textPath(String(i + 1), x + p[0] * s - 28, y + p[1] * s - 12, {
      size: 26,
      bold: true,
      fill: BRAND.primaryDark,
      anchor: 'middle',
    });
    parts.push(label.svg);
  }

  // Decorations: soft sun circles, little stars.
  const deco = [
    `<circle cx="960" cy="40" r="120" fill="${BRAND.sun}" opacity="0.45"/>`,
    `<circle cx="40" cy="470" r="90" fill="${BRAND.sun}" opacity="0.4"/>`,
    star(548, 96, 16, BRAND.accent),
    star(900, 432, 12, BRAND.accent),
    star(596, 440, 10, BRAND.primary),
  ];

  // Name, then a plain description (no claims). Each line shrinks to fit the text column.
  const tx = 588;
  const maxW = 930 - tx;
  const muted = { fill: BRAND.textMuted };
  const text = [
    await fitText('আখৰ খেল', tx, 212, { size: 100, bold: true, fill: BRAND.primaryDark }, maxW),
    await fitText('Akhor Khel', tx + 4, 284, { size: 56, bold: true, fill: BRAND.text }, maxW),
    await fitText('আঁচে আঁচে ক খ লিখিবলৈ শিকক', tx + 4, 342, { size: 28, ...muted }, maxW),
    await fitText('Trace each letter, stroke by stroke', tx + 4, 382, { size: 26, ...muted }, maxW),
  ];

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">` +
    `<rect width="${W}" height="${H}" fill="${BRAND.background}"/>` +
    deco.join('') +
    parts.join('') +
    mascotAt(338, 246, 236, true) +
    text.join('') +
    `</svg>`
  );
}

/** A line of text, shrunk until it fits `maxWidth`. */
async function fitText(
  text: string,
  x: number,
  baseline: number,
  style: TextStyle,
  maxWidth: number,
): Promise<string> {
  let t = await textPath(text, x, baseline, style);
  if (t.width > maxWidth) {
    t = await textPath(text, x, baseline, { ...style, size: (style.size * maxWidth) / t.width });
  }
  return t.svg;
}

function star(cx: number, cy: number, r: number, fill: string): string {
  const pts: string[] = [];
  for (let i = 0; i < 10; i++) {
    const rad = i % 2 === 0 ? r : r * 0.45;
    const a = (Math.PI / 5) * i - Math.PI / 2;
    pts.push(`${(cx + rad * Math.cos(a)).toFixed(1)},${(cy + rad * Math.sin(a)).toFixed(1)}`);
  }
  return `<polygon points="${pts.join(' ')}" fill="${fill}"/>`;
}

// ---- Main --------------------------------------------------------------------------------------

function write(file: string, data: Buffer | string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
  console.warn(`✎ ${path.relative(ROOT, file).replace(/\\/g, '/')}`);
}

async function main() {
  const ka = await glyphUnit('ক', 'NotoSansBengali-Bold.ttf');

  // Play icon (full square; Play applies its own mask and shadow).
  const icon = iconSvg(ka, { background: true, shape: 'square' });
  write(path.join(BRAND_DIR, 'icon.svg'), icon + '\n');
  write(path.join(OUT_DIR, 'icon-512.png'), (await render(icon, 512)).png);

  // Feature graphic: 24-bit, no alpha.
  const feature = await featureSvg();
  write(path.join(BRAND_DIR, 'feature-graphic.svg'), feature + '\n');
  const fg = await render(feature, 1024);
  write(
    path.join(OUT_DIR, 'feature-graphic-1024x500.png'),
    encodeRgbPng(1024, 500, fg.pixels, BRAND.background),
  );

  // Launcher icons.
  const legacy = iconSvg(ka, { background: true, shape: 'rounded' });
  const round = iconSvg(ka, { background: true, shape: 'circle' });
  const fore = foregroundSvg(ka);
  for (const [name, scale] of Object.entries(DENSITIES)) {
    const dir = path.join(RES_DIR, `mipmap-${name}`);
    write(path.join(dir, 'ic_launcher.png'), (await render(legacy, 48 * scale)).png);
    write(path.join(dir, 'ic_launcher_round.png'), (await render(round, 48 * scale)).png);
    write(path.join(dir, 'ic_launcher_foreground.png'), (await render(fore, 108 * scale)).png);
  }
  write(path.join(RES_DIR, 'mipmap-anydpi-v26/ic_launcher.xml'), ADAPTIVE_XML);
  write(path.join(RES_DIR, 'mipmap-anydpi-v26/ic_launcher_round.xml'), ADAPTIVE_XML);
  write(path.join(RES_DIR, 'drawable/ic_launcher_monochrome.xml'), monochromeXml(ka));
  write(path.join(RES_DIR, 'values/ic_launcher_background.xml'), BACKGROUND_XML);
}

if (require.main === module) {
  main().catch(e => {
    console.error(e);
    process.exit(1);
  });
}
