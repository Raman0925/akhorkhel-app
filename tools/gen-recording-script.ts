/**
 * Recording script generator. `npm run gen:recording-script`
 *
 * Writes docs/RECORDING_SCRIPT.md from the registered packs and the voice prompt list
 * (src/audio/prompts.ts): every audio file the app expects, what to say, and whether it exists.
 * Re-run after changing a pack or PROMPTS; the output is deterministic.
 */
import fs from 'node:fs';
import path from 'node:path';

import { PROMPTS } from '../src/audio/prompts';
import type { PackContent } from '../src/content/schema';

import { registeredPackIds } from './glyph-geometry';

const ROOT = path.resolve(__dirname, '..');
const PACKS_DIR = path.join(ROOT, 'src/content/packs');
const OUT = path.join(ROOT, 'docs/RECORDING_SCRIPT.md');

type Row = { file: string; say: string; note: string };

const cell = (s: string) => s.replace(/\|/g, '\\|');
const table = (rows: Row[], exists: (file: string) => boolean) =>
  [
    '| File | Say | Notes | Recorded |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      r =>
        `| \`${r.file}\` | ${cell(r.say)} | ${cell(r.note)} | ${exists(r.file) ? 'yes' : 'no'} |`,
    ),
  ].join('\n');

export function packRows(pack: PackContent): { title: string; rows: Row[] }[] {
  const groups: { title: string; rows: Row[] }[] = [
    {
      title: 'Letters',
      rows: [...pack.letters]
        .sort((a, b) => a.order - b.order)
        .map(l => ({ file: l.audio, say: l.glyph, note: `letter ${l.id} (${l.group})` })),
    },
    {
      title: 'Vowel signs',
      rows: (pack.signs ?? []).map(s => ({
        file: s.audio,
        say: s.result,
        note: `${s.base} + ${s.sign}`,
      })),
    },
    {
      title: 'Numbers',
      rows: pack.numbers.map(n => ({
        file: n.audio,
        say: n.word ? `${n.numeral} (${n.word})` : n.numeral,
        note: n.word ? `number ${n.value}` : `number ${n.value}: number word still needed`,
      })),
    },
    {
      title: 'Words',
      rows: pack.words.map(w => ({
        file: w.audio,
        say: w.text,
        note: [w.bridge?.en, w.bonus ? 'bonus' : ''].filter(Boolean).join(', '),
      })),
    },
  ];
  return groups.filter(g => g.rows.length > 0);
}

export function recordingScript(
  packs: PackContent[],
  prompts: Record<string, { as: string; en: string }>,
  exists: (packId: string, file: string) => boolean,
): string {
  const out: string[] = [
    '# Recording script',
    '',
    '<!-- GENERATED by tools/gen-recording-script.ts. Do not edit by hand. Run `npm run gen:recording-script`. -->',
    '',
    'Every audio file the app plays. Record to the spec in [CONTENT_GUIDE.md](CONTENT_GUIDE.md#audio)',
    '(44.1 kHz WAV master, delivered as mono AAC `.m4a`), name each file exactly as listed and put it',
    'at the listed path inside `src/content/packs/<packId>/` (pack audio) or `src/audio/prompts/`',
    '(voice prompts). Then run `npm run gen:assets`.',
    '',
    'All text below comes from draft packs (`draft-needs-native-review`): the reviewer confirms each',
    'item before it is recorded.',
    '',
  ];
  for (const pack of packs) {
    out.push(`## ${pack.language.nameEn} (\`${pack.id}\`): ${pack.status}`, '');
    const groups = packRows(pack);
    if (groups.length === 0) {
      out.push('Nothing to record yet: the pack has no content.', '');
      continue;
    }
    for (const g of groups) {
      out.push(
        `### ${g.title}`,
        '',
        table(g.rows, f => exists(pack.id, f)),
        '',
      );
    }
  }
  out.push('## Voice prompts', '');
  out.push(
    'Recorded once per UI language. The Assamese text must be checked by a native speaker first.',
    '',
  );
  const ids = Object.keys(prompts);
  for (const lang of ['as', 'en'] as const) {
    out.push(`### ${lang === 'as' ? 'Assamese' : 'English'} (\`src/audio/prompts/${lang}/\`)`, '');
    out.push(
      table(
        ids.map(id => ({
          file: `${lang}/${id}.m4a`,
          say: (prompts[id] as { as: string; en: string })[lang],
          note: id,
        })),
        f => exists('prompts', f),
      ),
      '',
    );
  }
  return out.join('\n');
}

async function main() {
  const ids = registeredPackIds(fs.readFileSync(path.join(PACKS_DIR, 'index.ts'), 'utf8'));
  const packs = ids.map(
    id => JSON.parse(fs.readFileSync(path.join(PACKS_DIR, id, 'pack.json'), 'utf8')) as PackContent,
  );
  const md = recordingScript(packs, PROMPTS, (packId, file) =>
    fs.existsSync(
      packId === 'prompts'
        ? path.join(ROOT, 'src/audio/prompts', file)
        : path.join(PACKS_DIR, packId, file),
    ),
  );
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  const formatted = await prettier.format(md, { ...options, filepath: OUT });
  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (before !== formatted) {
    fs.writeFileSync(OUT, formatted);
  }
  console.warn(`${before === formatted ? '=' : '✎'} docs/RECORDING_SCRIPT.md`);
}

if (require.main === module) {
  main().catch(e => {
    console.error(e);
    process.exit(1);
  });
}
