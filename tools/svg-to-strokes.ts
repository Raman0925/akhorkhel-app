/**
 * svg-to-strokes: turn a hand-made SVG of centreline strokes into tracing strokes (owner A2).
 *
 * The SVG's <path> elements are the pen strokes in writing order (each subpath, i.e. each M, is one
 * stroke). Supported path commands: M L H V C S Q T Z, absolute and relative. Curves are flattened,
 * points are normalised to 0..1 with the SVG viewBox (uniform scale, the shorter side centred, y down)
 * and simplified.
 *
 *   npx tsx tools/svg-to-strokes.ts ka.svg --key letter:ka                 print { "letter:ka": { strokes } }
 *   npx tsx tools/svg-to-strokes.ts ka.svg --key letter:ka --pack asm-beng merge into geometry.json
 *
 * Merging keeps the entry's text and outline (generated by tools/glyph-geometry.ts), replaces its
 * strokes and marks it `strokeSource: "recorded"` so tools never overwrite it.
 */
import fs from 'node:fs';
import path from 'node:path';

import { simplifyStroke, type Vec } from '../src/features/tracing/scorer/geometry';

export type ViewBox = { minX: number; minY: number; width: number; height: number };
export type PathCommand = { cmd: string; args: number[] };
export type StrokeOut = { points: [number, number][] };

const ARG_COUNT: Record<string, number> = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, Z: 0 };

/** Tokenise SVG path data into commands with their numeric arguments (implicit repeats expanded). */
export function parsePathData(d: string): PathCommand[] {
  const tokens = d.match(/[a-zA-Z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g) ?? [];
  const out: PathCommand[] = [];
  let i = 0;
  let cmd = '';
  while (i < tokens.length) {
    const t = tokens[i] as string;
    if (/^[a-zA-Z]$/.test(t)) {
      cmd = t;
      i++;
      if (!(cmd.toUpperCase() in ARG_COUNT)) {
        throw new Error(`Unsupported path command "${cmd}" (use M L H V C S Q T Z)`);
      }
      if (cmd.toUpperCase() === 'Z') {
        out.push({ cmd, args: [] });
        continue;
      }
    } else if (!cmd) {
      throw new Error(`Path data must start with a command: "${d.slice(0, 20)}"`);
    }
    const n = ARG_COUNT[cmd.toUpperCase()] as number;
    if (n === 0) {
      throw new Error(`Unexpected number after Z in "${d.slice(0, 20)}"`);
    }
    const args: number[] = [];
    while (args.length < n && i < tokens.length && !/^[a-zA-Z]$/.test(tokens[i] as string)) {
      args.push(Number(tokens[i]));
      i++;
    }
    if (args.length < n) {
      throw new Error(`Command "${cmd}" needs ${n} numbers in "${d.slice(0, 20)}"`);
    }
    out.push({ cmd, args });
    // Extra coordinate pairs after M/m are implicit L/l.
    if (cmd === 'M') {
      cmd = 'L';
    } else if (cmd === 'm') {
      cmd = 'l';
    }
  }
  return out;
}

function cubic(p0: Vec, p1: Vec, p2: Vec, p3: Vec, t: number): Vec {
  const u = 1 - t;
  const a = u * u * u;
  const b = 3 * u * u * t;
  const c = 3 * u * t * t;
  const e = t * t * t;
  return [
    a * p0[0] + b * p1[0] + c * p2[0] + e * p3[0],
    a * p0[1] + b * p1[1] + c * p2[1] + e * p3[1],
  ];
}

function quad(p0: Vec, p1: Vec, p2: Vec, t: number): Vec {
  const u = 1 - t;
  return [
    u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0],
    u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1],
  ];
}

/** Flatten path data into polylines (one per subpath) in SVG user units. */
export function flattenPath(d: string, segmentsPerCurve = 16): Vec[][] {
  const lines: Vec[][] = [];
  let line: Vec[] = [];
  let cur: Vec = [0, 0];
  let start: Vec = [0, 0];
  let lastCtrl: Vec | null = null;
  let lastCmd = '';
  const flush = () => {
    if (line.length > 0) {
      lines.push(line);
    }
    line = [];
  };
  const addCurve = (f: (t: number) => Vec) => {
    for (let k = 1; k <= segmentsPerCurve; k++) {
      line.push(f(k / segmentsPerCurve));
    }
  };

  for (const { cmd, args: a } of parsePathData(d)) {
    const rel = cmd === cmd.toLowerCase();
    const C = cmd.toUpperCase();
    const ox = rel ? cur[0] : 0;
    const oy = rel ? cur[1] : 0;
    const pt = (x: number, y: number): Vec => [ox + x, oy + y];
    let ctrl: Vec | null = null;
    switch (C) {
      case 'M':
        flush();
        cur = pt(a[0] as number, a[1] as number);
        start = cur;
        line.push(cur);
        break;
      case 'L':
        cur = pt(a[0] as number, a[1] as number);
        line.push(cur);
        break;
      case 'H':
        cur = [(rel ? cur[0] : 0) + (a[0] as number), cur[1]];
        line.push(cur);
        break;
      case 'V':
        cur = [cur[0], (rel ? cur[1] : 0) + (a[0] as number)];
        line.push(cur);
        break;
      case 'C':
      case 'S': {
        const p0: Vec = cur;
        const reflect: Vec =
          lastCtrl && (lastCmd === 'C' || lastCmd === 'S')
            ? [2 * p0[0] - lastCtrl[0], 2 * p0[1] - lastCtrl[1]]
            : p0;
        const p1 = C === 'C' ? pt(a[0] as number, a[1] as number) : reflect;
        const rest = C === 'C' ? a.slice(2) : a;
        const p2 = pt(rest[0] as number, rest[1] as number);
        const p3 = pt(rest[2] as number, rest[3] as number);
        addCurve(t => cubic(p0, p1, p2, p3, t));
        cur = p3;
        ctrl = p2;
        break;
      }
      case 'Q':
      case 'T': {
        const p0: Vec = cur;
        const p1: Vec =
          C === 'Q'
            ? pt(a[0] as number, a[1] as number)
            : lastCtrl && (lastCmd === 'Q' || lastCmd === 'T')
              ? ([2 * p0[0] - lastCtrl[0], 2 * p0[1] - lastCtrl[1]] as Vec)
              : p0;
        const p2 =
          C === 'Q' ? pt(a[2] as number, a[3] as number) : pt(a[0] as number, a[1] as number);
        addCurve(t => quad(p0, p1, p2, t));
        cur = p2;
        ctrl = p1;
        break;
      }
      case 'Z':
        cur = start;
        line.push(start);
        break;
    }
    lastCtrl = ctrl;
    lastCmd = C;
  }
  flush();
  return lines;
}

function attr(tag: string, name: string): string | undefined {
  const m = new RegExp(`\\s${name}\\s*=\\s*("([^"]*)"|'([^']*)')`).exec(tag);
  return m ? (m[2] ?? m[3]) : undefined;
}

/** The viewBox and the `d` of every <path> in document order. */
export function parseSvg(svg: string): { viewBox: ViewBox; paths: string[] } {
  const svgTag = /<svg\b[^>]*>/i.exec(svg)?.[0];
  if (!svgTag) {
    throw new Error('No <svg> element found');
  }
  let viewBox: ViewBox | undefined;
  const vb = attr(svgTag, 'viewBox');
  if (vb) {
    const [minX, minY, width, height] = vb
      .split(/[\s,]+/)
      .filter(Boolean)
      .map(Number);
    if ([minX, minY, width, height].every(v => typeof v === 'number' && Number.isFinite(v))) {
      viewBox = {
        minX: minX as number,
        minY: minY as number,
        width: width as number,
        height: height as number,
      };
    }
  } else {
    const w = parseFloat(attr(svgTag, 'width') ?? '');
    const h = parseFloat(attr(svgTag, 'height') ?? '');
    if (Number.isFinite(w) && Number.isFinite(h)) {
      viewBox = { minX: 0, minY: 0, width: w, height: h };
    }
  }
  if (!viewBox || viewBox.width <= 0 || viewBox.height <= 0) {
    throw new Error('The <svg> needs a viewBox (or width and height)');
  }
  const paths: string[] = [];
  for (const m of svg.matchAll(/<path\b[^>]*>/gi)) {
    const d = attr(m[0], 'd');
    if (d && d.trim()) {
      paths.push(d);
    }
  }
  return { viewBox, paths };
}

/** Map SVG user units into the unit box: uniform scale, shorter side centred. */
export function normalise(p: Vec, vb: ViewBox): Vec {
  const size = Math.max(vb.width, vb.height);
  const dx = (size - vb.width) / 2;
  const dy = (size - vb.height) / 2;
  return [(p[0] - vb.minX + dx) / size, (p[1] - vb.minY + dy) / size];
}

/** SVG text → tracing strokes (normalised, simplified), in writing order. */
export function svgToStrokes(svg: string, epsilon = 0.004, maxPoints = 40): StrokeOut[] {
  const { viewBox, paths } = parseSvg(svg);
  const strokes: StrokeOut[] = [];
  for (const d of paths) {
    for (const poly of flattenPath(d)) {
      const points = simplifyStroke(
        poly.map(p => normalise(p, viewBox)),
        epsilon,
        maxPoints,
      );
      if (points.length >= 2) {
        strokes.push({ points });
      }
    }
  }
  if (strokes.length === 0) {
    throw new Error('No strokes found: add <path d="..."> elements');
  }
  return strokes;
}

type GeometryEntry = {
  text: string;
  outline: string;
  strokes: StrokeOut[];
  strokeSource: string;
};

/** Merge strokes into a geometry file object (returns a new object; the key must already exist). */
export function mergeStrokes(
  geometry: Record<string, GeometryEntry>,
  key: string,
  strokes: StrokeOut[],
): Record<string, GeometryEntry> {
  const entry = geometry[key];
  if (!entry) {
    throw new Error(
      `No geometry entry for "${key}". Generate its outline first (tools/glyph-geometry.ts).`,
    );
  }
  return { ...geometry, [key]: { ...entry, strokes, strokeSource: 'recorded' } };
}

function argValue(argv: string[], name: string): string | undefined {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
}

async function main(argv: string[]): Promise<void> {
  const file = argv.find((a, i) => !a.startsWith('--') && !argv[i - 1]?.startsWith('--'));
  const key = argValue(argv, '--key');
  const pack = argValue(argv, '--pack');
  if (!file || !key) {
    console.error(
      'Usage: npx tsx tools/svg-to-strokes.ts <file.svg> --key <letter:id|sign:id|number:n> [--pack <packId>]',
    );
    process.exit(2);
  }
  const strokes = svgToStrokes(fs.readFileSync(file, 'utf8'));
  const prettier = await import('prettier');
  if (!pack) {
    const text = await prettier.format(JSON.stringify({ [key]: { strokes } }), {
      parser: 'json',
      printWidth: 100,
    });
    process.stdout.write(text);
    return;
  }
  const geoPath = path.resolve(__dirname, '..', 'src/content/packs', pack, 'geometry.json');
  const geometry = JSON.parse(fs.readFileSync(geoPath, 'utf8')) as Record<string, GeometryEntry>;
  const merged = mergeStrokes(geometry, key, strokes);
  const options = (await prettier.resolveConfig(geoPath)) ?? {};
  const text = await prettier.format(JSON.stringify(merged), { ...options, filepath: geoPath });
  fs.writeFileSync(geoPath, text);
  console.warn(
    `✓ ${key}: ${strokes.length} strokes written to ${path.relative(process.cwd(), geoPath)}`,
  );
}

if (require.main === module) {
  main(process.argv.slice(2)).catch((e: unknown) => {
    console.error(`✗ ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
