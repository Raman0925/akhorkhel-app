/**
 * Content schema: the contract between content (humans) and the app (code).
 * FROZEN (owner A0). Change only through an ADR in docs/adr.
 *
 * A pack lives in src/content/packs/<packId>/:
 *   pack.json      human-authored content (letters, signs, words, numbers)
 *   geometry.json  tool-maintained outlines + strokes per glyph (tools/glyph-geometry.ts);
 *                  entries with strokeSource "recorded"/"reviewed" are never overwritten by tools
 *   audio/...      AAC (.m4a) files, named by item id
 *   images/...     word pictures (.webp/.png)
 *
 * The runtime app imports only the TypeScript types from this file (`import type`), so zod is never
 * bundled into the app. Tools and tests use the zod schemas to validate.
 */
import { z } from 'zod';

/** Pack ID = ISO 639-3 + ISO 15924 script, lower case, e.g. asm-beng, brx-deva, mrg-latn. */
export const PACK_ID_RE = /^[a-z]{3}-[a-z]{4}$/;
/** Item IDs are lower-case ASCII so they work as file names. */
export const ITEM_ID_RE = /^[a-z0-9][a-z0-9_-]*$/;

/** A point in the glyph box, normalised 0..1 (x right, y down). */
export const PointSchema = z.tuple([z.number().min(0).max(1), z.number().min(0).max(1)]);
/** One pen stroke, ordered from start to end. */
export const StrokeSchema = z.object({ points: z.array(PointSchema).min(2) });

export const ScriptSchema = z.enum(['Latn', 'Deva', 'Beng']);
export const PackStatusSchema = z.enum(['verified', 'draft-needs-native-review']);

export const ReviewerSchema = z.object({
  name: z.string().min(1),
  org: z.string().min(1),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
});

const audioPath = z.string().regex(/^audio\/[a-z0-9/_-]+\.m4a$/, 'audio must be audio/<path>.m4a');
const imagePath = z
  .string()
  .regex(/^images\/[a-z0-9/_-]+\.(webp|png)$/, 'image must be images/<path>.webp|png');

export const LetterContentSchema = z.object({
  id: z.string().regex(ITEM_ID_RE),
  glyph: z.string().min(1),
  group: z.enum(['vowel', 'consonant', 'other']),
  order: z.number().int().nonnegative(),
  audio: audioPath,
  exampleWordId: z.string().regex(ITEM_ID_RE).optional(),
});

export const SignContentSchema = z.object({
  id: z.string().regex(ITEM_ID_RE),
  /** Base consonant, e.g. ক */
  base: z.string().min(1),
  /** The sign on its own (with dotted circle when displayed alone), e.g. া */
  sign: z.string().min(1),
  /** The combined syllable, e.g. কা */
  result: z.string().min(1),
  audio: audioPath,
});

export const WordContentSchema = z.object({
  id: z.string().regex(ITEM_ID_RE),
  text: z.string().min(1),
  audio: audioPath,
  image: imagePath,
  /** Letter id this word starts with (used by the "which picture starts with" game). */
  startsWith: z.string().regex(ITEM_ID_RE).optional(),
  /** Bridge card: the same word in Assamese and English (for Bodo/Mising packs). */
  bridge: z.object({ as: z.string().optional(), en: z.string().optional() }).optional(),
  /** Bonus words are unlocked for 24 h by a parent via a rewarded ad (handover 3.2). */
  bonus: z.boolean().optional(),
  /** Draft packs only: emoji shown until the real illustration exists. Rejected in release. */
  placeholderEmoji: z.string().optional(),
});

export const NumberContentSchema = z.object({
  value: z.number().int().min(0).max(100),
  numeral: z.string().min(1),
  /** Number word (e.g. এক). Optional until a native speaker supplies it; required for release. */
  word: z.string().min(1).optional(),
  audio: audioPath,
});

export const PackContentSchema = z.object({
  id: z.string().regex(PACK_ID_RE),
  language: z.object({
    iso639_3: z.string().regex(/^[a-z]{3}$/),
    nameNative: z.string().min(1),
    nameEn: z.string().min(1),
    nameAs: z.string().min(1),
  }),
  script: ScriptSchema,
  fontFamily: z.string().min(1),
  status: PackStatusSchema,
  reviewedBy: z.array(ReviewerSchema).optional(),
  /** Where the content came from (alphabet authority, primer used as reference, etc.). */
  sources: z.array(z.string()).optional(),
  letters: z.array(LetterContentSchema),
  signs: z.array(SignContentSchema).optional(),
  words: z.array(WordContentSchema),
  numbers: z.array(NumberContentSchema),
});

export const StrokeSourceSchema = z.enum(['auto', 'reviewed', 'recorded']);

export const GlyphGeometrySchema = z.object({
  /** The text that was shaped (for change detection). */
  text: z.string().min(1),
  /** SVG path data of the glyph outline in the unit box (0..1), y down. */
  outline: z.string().min(1),
  strokes: z.array(StrokeSchema),
  /**
   * auto     = generated by tools/glyph-geometry.ts (placeholder stroke order, needs review)
   * reviewed = auto strokes checked and approved by a native writer
   * recorded = recorded by a native writer in the Stroke Recorder
   */
  strokeSource: StrokeSourceSchema,
});

/** Keys: `letter:<id>`, `sign:<id>`, `number:<value>`. */
export const GeometryFileSchema = z.record(z.string(), GlyphGeometrySchema);

export type Point = z.infer<typeof PointSchema>;
export type Stroke = z.infer<typeof StrokeSchema>;
export type Script = z.infer<typeof ScriptSchema>;
export type PackStatus = z.infer<typeof PackStatusSchema>;
export type Reviewer = z.infer<typeof ReviewerSchema>;
export type StrokeSource = z.infer<typeof StrokeSourceSchema>;
export type GlyphGeometry = z.infer<typeof GlyphGeometrySchema>;
export type GeometryFile = z.infer<typeof GeometryFileSchema>;
export type PackContent = z.infer<typeof PackContentSchema>;

/** Something the child can trace. */
export type Traceable = {
  /** Unique within the pack: `letter:<id>`, `sign:<id>` or `number:<value>`. */
  key: string;
  /** Text to show big (glyph, syllable or numeral). */
  display: string;
  outline: string;
  strokes: Stroke[];
  strokeSource: StrokeSource;
};

/** Runtime shapes after the loader merges pack.json + geometry.json + asset manifest. */
export type Letter = z.infer<typeof LetterContentSchema> & Traceable;
export type Sign = z.infer<typeof SignContentSchema> & Traceable;
export type Word = z.infer<typeof WordContentSchema>;
export type NumberItem = z.infer<typeof NumberContentSchema> & Traceable;

export type Pack = Omit<PackContent, 'letters' | 'signs' | 'words' | 'numbers'> & {
  letters: Letter[];
  signs: Sign[];
  words: Word[];
  numbers: NumberItem[];
};

export { letterKey, signKey, numberKey } from './keys';
